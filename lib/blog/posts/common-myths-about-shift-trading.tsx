export default function Body() {
  return (
    <>
      <p>
        Shift trading collects myths the way group chats collect unread messages. A few of the
        most common ones are worth retiring.
      </p>

      <h2>&ldquo;It always creates overtime and payroll problems&rdquo;</h2>
      <p>
        It creates problems when trades are untracked or when people ignore thresholds. When
        trades are recorded and approval still sits with the scheduler, overtime is visible before
        it becomes a surprise. The problem is uncontrolled trading, not trading itself.
      </p>

      <h2>&ldquo;Only unreliable people need to trade&rdquo;</h2>
      <p>
        People trade because life is irregular: childcare, second jobs, health, family, school,
        transportation. Treating trading as a character signal misreads the reason most shifts
        move. The unreliable minority exist in every system; they are not the majority of people
        posting.
      </p>

      <h2>&ldquo;Managers always hate it&rdquo;</h2>
      <p>
        Many managers hate the chaos of informal cover arrangements. A visible, role-aware board
        with clear confirmation steps often reduces their workload. Resistance is more common when
        trading looks like a parallel authority than when it looks like an organized way to keep
        shifts covered.
      </p>

      <h2>&ldquo;Equal hours always means a fair trade&rdquo;</h2>
      <p>
        Hours are a poor unit. Premiums, rest, difficulty, and travel change the real cost.
        Fairness is closer to both people understanding what they are agreeing to than to the
        clock times matching.
      </p>

      <h2>&ldquo;If you post it, someone will take it&rdquo;</h2>
      <p>
        Only if the post is clear, early, and accurate. Vague last-minute posts fail for
        structural reasons, not because the team is unhelpful.
      </p>
      <p>
        Trading works when the process is clear and the medium supports it. The myths mostly
        describe what happens when the process is unclear and the medium is a chat.
      </p>
    </>
  )
}
