    <>
      <p>
        A board without a few clear rules slowly fills with the same problems that made group
        chats fail: last-minute chaos, unqualified claims, ambiguous agreements, and no path when
        something goes wrong. The rules do not need to be long. They need to be known and enforced
        lightly but consistently.
      </p>

      <h2>A working set</h2>
      <ul>
        <li>Only verified members of the workplace (or the specific team) can post and claim.</li>
        <li>Posts must include date, hours, role, and whether it is a giveaway, swap, or request.</li>
        <li>Claims are confirmed by both parties; the shift stays with the original person until the official approval is recorded.</li>
        <li>You may only claim shifts you are qualified and signed off to work.</li>
        <li>Last-minute posts (under 24 hours) should include a brief reason.</li>
        <li>If a claimed shift is not worked, the original poster and the claimant both have a responsibility to notify the scheduler; patterns of no-shows are escalated.</li>
        <li>Disputes go to the board moderator or the relevant supervisor, not to the public thread.</li>
      </ul>

      <h2>Why these particular rules</h2>
      <p>
        They target the failure modes that actually damage trust: people claiming shifts they
        cannot work, agreements that were never solid, and silent failures that leave a shift
        uncovered. Everything else is secondary.
      </p>

      <h2>How to introduce them</h2>
      <p>
        Put them somewhere visible &mdash; a pinned post, a short document linked from the board, a
        note on the welcome message for new members. Do not assume people will absorb them by
        osmosis. New starters especially need them written down.
      </p>

      <h2>Enforcement</h2>
      <p>
        Most of the time a quiet reminder is enough. Repeated problems &mdash; always posting at
        the last minute without reason, claiming shifts outside qualification, agreeing and then
        disappearing &mdash; are worth a private conversation and, if necessary, a temporary
        restriction. Public call-outs usually create more heat than light.
      </p>
      <p>
        Rules that are published and occasionally applied keep the board usable. Rules that exist
        only in someone&rsquo;s head do not.
      </p>
    </>
